import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import { env } from './config/env.js';
import { requestContext } from './middleware/request-context.js';
import { requestLogger } from './middleware/request-logger.js';
import { originGuard } from './middleware/origin-guard.js';
import { errorHandler } from './shared/errors/error-handler.js';
import { authRouter } from './modules/auth/routes/auth.routes.js';
import { healthRouter } from './modules/health/routes/health.routes.js';
import { authenticate, requireTenant } from './middleware/authenticate.js';
import { requireRoles } from './middleware/authorize-role.js';
import { customerRouter } from './modules/customer/customer.routes.js';
import { managementRouter } from './modules/management/management.routes.js';
import { waiterRouter } from './modules/waiter/waiter.routes.js';
import { kitchenRouter } from './modules/kitchen/kitchen.routes.js';
import { cashierRouter } from './modules/cashier/cashier.routes.js';
import { analyticsRouter } from './modules/analytics/analytics.routes.js';
export const app = express();
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({ origin: env.WEB_ORIGIN, credentials: true, methods: ['GET', 'POST', 'PATCH', 'PUT', 'DELETE', 'OPTIONS'], allowedHeaders: ['Content-Type', 'X-Restaurant-Id', 'X-Branch-Id', 'Idempotency-Key', 'X-Guest-Order-Token'] }));
app.use(express.json({ limit: '1mb' }));
app.use(cookieParser());
app.use(requestContext);
app.use(requestLogger);
app.use(originGuard);
app.get('/health', (_req, res) => res.redirect(308, '/api/v1/health'));
app.use('/api/v1/health', healthRouter);
app.use('/api/v1/auth', authRouter);
app.use('/api/v1', customerRouter);
app.use('/api/v1', managementRouter);
app.use('/api/v1', waiterRouter);
app.use('/api/v1', kitchenRouter);
app.use('/api/v1', cashierRouter);
app.use('/api/v1', analyticsRouter);
app.get('/api/v1/tenant/context', authenticate, requireTenant, (req, res) => res.json({ tenant: req.tenant }));
app.get('/api/v1/tenant/management-context', authenticate, requireTenant, requireRoles('RESTAURANT_OWNER', 'MANAGER'), (req, res) => res.json({ tenant: req.tenant, permissions: ['restaurant:manage'] }));
app.use((_req, res) => res.status(404).json({ error: { code: 'NOT_FOUND', message: 'Route not found', requestId: res.getHeader('X-Request-Id') } }));
app.use(errorHandler);
